/* HUDDLE colour palette: the Super Nintendo hardware colours from the original
 * Python version (huddle.py, SNES_COLORS). Values are 0xRRGGBB. */
#ifndef HUDDLE_PALETTE_H
#define HUDDLE_PALETTE_H

#define SNES_LIGHT_GRAY 0xcfcfcf /* console body                  */
#define SNES_DARK_GRAY  0x7f7f7f /* header / accent strips        */
#define SNES_PURPLE     0x6b4ca5 /* primary action colour         */
#define SNES_LAVENDER   0xb19cd9 /* secondary panels / text areas */
#define SNES_WARNING    0xe5b567 /* soft highlight for status     */
#define SNES_WHITE      0xffffff
#define SNES_BLACK      0x000000

#endif
